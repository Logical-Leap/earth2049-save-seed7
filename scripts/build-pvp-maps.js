/* Build the match server's copy of every PvP map: colliders, spawns, objectives and nav graph, from the level layouts.
 *   node scripts/build-pvp-maps.js          writes workers/pvp-maps.generated.js
 *   node scripts/build-pvp-maps.js --check  fails if the file is out of date (run by npm test)
 * The browser builds the same data at runtime from the layout it already loaded (PvpSim.mapFromLayout). */
'use strict';
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..');
const PVP = require(path.join(root, 'js/pvp/pvp-data.js'));
const Sim = require(path.join(root, 'js/pvp/pvp-sim.js'));
const out = path.join(root, 'workers/pvp-maps.generated.js');
const maps = {};
for (const id of PVP.MAP_ORDER) {
  const L = JSON.parse(fs.readFileSync(path.join(root, `assets/maps/${id}/${id}.layout.json`), 'utf8'));
  maps[id] = Sim.mapFromLayout(L, id);
}
const body = '// GENERATED by scripts/build-pvp-maps.js from assets/maps/*/*.layout.json. Do not edit by hand.\n' +
  'export const PVP_MAPS = ' + JSON.stringify(maps) + ';\n';
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
  if (cur !== body) { console.error('workers/pvp-maps.generated.js is out of date: run node scripts/build-pvp-maps.js'); process.exit(1); }
  console.log('PvP map data up to date');
} else {
  fs.writeFileSync(out, body);
  console.log(`wrote ${path.relative(root, out)} (${(body.length / 1024).toFixed(0)} KiB, ${Object.keys(maps).length} maps)`);
}
